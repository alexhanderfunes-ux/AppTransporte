    private void btnactualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnactualizarActionPerformed
       if (idcamion==0){
            JOptionPane.showMessageDialog(this,"Por favor selecciona un camion de la tabla");
            return;
           } 
        try {
                
                Camion camion = new Camion();
                camion.setModelo(txtmodelo.getText());
                camion.setIdCamion(idcamion);
                camion.setTipo(txtTipo.getText());
                camion.setNoPlaca(txtnumplaca.getText());
                camion.setPotencia(Integer.parseInt(txtpotencia.getText()));
                
                CamionDAO daoac = new CamionDAO();
                daoac.Actualizar(camion);
                JOptionPane.showMessageDialog(this,"Datos actualizados correctamente");
                idcamion = 0; 
                txtmodelo.setText("");
                txtid.setText("");
                txtnumplaca.setText("");
                txtTipo.setText("");
                txtpotencia.setText("");
                tblcamion.clearSelection();
                cargarCamion();
            }
            catch (SQLException exp){
        }
    } 
    
    private void cargarCamion(){
    CamionDAO listarCamion = new CamionDAO();
    try{
        List<Camion> lista = listarCamion.listar();
        DefaultTableModel modelo = (DefaultTableModel) tblcamion.getModel();
        
        modelo.setRowCount(0);
        for (Camion c: lista){
            modelo.addRow(new Object[]{
            c.getIdCamion(),
            c.getNoPlaca(),
            c.getModelo(),
            c.getTipo(),
            c.getPotencia()
        });
        }
         tblcamion.setModel(modelo);
         } catch (SQLException exp){
            
        }
    }//GEN-LAST:event_btnactualizarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
       if (idcamion==0){
            JOptionPane.showMessageDialog(this,"Por favor selecciona a un camion de la tabla");
            return;
        }
        int respuesta= JOptionPane.showConfirmDialog(this,"¿Esta seguro de que quiere eliminar el registro?","Confirmacion de Eliminacion",JOptionPane.YES_NO_OPTION,JOptionPane.QUESTION_MESSAGE);
        if (respuesta==JOptionPane.YES_OPTION){
           
          CamionDAO dao= new CamionDAO();
            try{
                dao.Eliminar(idcamion);
                JOptionPane.showMessageDialog(this,"Camion eliminado exitosamente");
                cargarCamion();
                idcamion = 0; 
                txtnumplaca.setText("");
                txtid.setText("");
                txtmodelo.setText("");
                txtTipo.setText("");
                txtpotencia.setText("");
                tblcamion.clearSelection();
            
             }catch(SQLException exp){
            
             }
        }
    }//GEN-LAST:event_btneliminarActionPerformed

