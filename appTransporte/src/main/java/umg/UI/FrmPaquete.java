    private void btnactualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnactualizarActionPerformed
     if (idpaquete==0){
            JOptionPane.showMessageDialog(this,"Por favor selecciona un registro de la tabla");
            return;
           } 
        try {
                
              Paquete paquete = new Paquete();
                paquete.setIdPaquete(idpaquete);
                paquete.setDescripcion(txtdescrip.getText());
                paquete.setDestinatario(txtdestinat.getText());
                paquete.setDireccion(txtdireccion.getText());
                 
                paquete.setIdcamionero(Integer.parseInt(txtidcamionero.getText()));
                paquete.setIdciudad(Integer.parseInt(txtidciudad.getText())); 
                
                PaqueteDAO daoac = new PaqueteDAO();
                daoac.Actualizar(paquete);
                JOptionPane.showMessageDialog(this,"Datos actualizados correctamente");
                idpaquete = 0; 
                txtdescrip.setText("");
                txtid.setText("");
                txtdireccion.setText("");
                txtdestinat.setText("");
                txtidcamionero.setText("");
                
                tblpaquete.clearSelection();
                cargarPaquete();
            }
            catch (SQLException exp){
        }
    } 
    private void cargarPaquete(){
    PaqueteDAO listarPaquete = new PaqueteDAO();
    try{
        List<Paquete> lista = listarPaquete.listar();
        DefaultTableModel modelo = (DefaultTableModel) tblpaquete.getModel();
        
        modelo.setRowCount(0);
        for (Paquete c: lista){
            modelo.addRow(new Object[]{
            c.getIdPaquete(),
            c.getDescripcion(),
            c.getDireccion(),
            c.getDestinatario(),
            c.getIdcamionero(),
            c.getIdciudad()
        });
        }
         tblpaquete.setModel(modelo);
         } catch (SQLException exp){
            
        }
    }//GEN-LAST:event_btnactualizarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
               if (idpaquete==0){
            JOptionPane.showMessageDialog(this,"Por favor selecciona un registro de la tabla");
            return;
        }
        int respuesta= JOptionPane.showConfirmDialog(this,"¿Esta seguro de que quiere eliminar el registro?","Confirmacion de Eliminacion",JOptionPane.YES_NO_OPTION,JOptionPane.QUESTION_MESSAGE);
        if (respuesta==JOptionPane.YES_OPTION){
           
          PaqueteDAO dao= new PaqueteDAO();
            try{
                dao.Eliminar(idpaquete);
                JOptionPane.showMessageDialog(this,"Registro eliminado exitosamente");
                cargarPaquete();
                idpaquete = 0; 
                txtdescrip.setText("");
                txtid.setText("");
                txtdireccion.setText("");
                txtdestinat.setText("");
                txtidcamionero.setText("");
                txtidciudad.setText("");
                tblpaquete.clearSelection();
            
             }catch(SQLException exp){
            
             }
        }

    }//GEN-LAST:event_btneliminarActionPerformed

    private void tblpaqueteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblpaqueteMouseClicked
       int fila = tblpaquete.getSelectedRow();
        if      (fila>0){
        idpaquete = Integer.parseInt(tblpaquete.getValueAt(fila, 0).toString());
        txtid.setText(tblpaquete.getValueAt(fila, 0).toString());
        txtdescrip.setText(tblpaquete.getValueAt(fila, 1).toString());
        txtdireccion.setText(tblpaquete.getValueAt(fila, 2).toString());
        txtdestinat.setText(tblpaquete.getValueAt(fila, 3).toString());
        txtidcamionero.setText(tblpaquete.getValueAt(fila, 4).toString());
        txtidciudad.setText(tblpaquete.getValueAt(fila,5).toString());}


    }//GEN-LAST:event_tblpaqueteMouseClicked

